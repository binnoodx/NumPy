# Introduction to Numpy

#Numpy is low level library written in C and Fortran. It is used for scientific computing and data analysis. It provides a powerful N-dimensional array object, and tools for working with these arrays.

#Numpy eliminates the slower algorithms of python

# At Past time , Python was not meant to be used in machine learning and data science because of its slow speed but Numpy was introduced with speed and performance of C and Comfort of Python. It is used for linear algebra, Fourier transform, and random number generation.

